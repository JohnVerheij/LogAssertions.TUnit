using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace LogAssertions.Generator;

/// <summary>Writes the generated class of one type: a <c>LogDefinition</c> field per method, built from literals.</summary>
internal static class SourceWriter
{
    /// <summary>The members a static class inherits from <see langword="object"/> that a field can hide: a field with one of
    /// these names is written with <see langword="new"/>. <c>Finalize</c> is not one: a static class cannot see it.</summary>
    private static readonly string[] ObjectMembers = ["Equals", "GetHashCode", "GetType", "MemberwiseClone", "ReferenceEquals", "ToString"];

    /// <summary>The names of the <c>LogLevel</c> values, indexed by value.</summary>
    private static readonly string[] LevelNames = ["Trace", "Debug", "Information", "Warning", "Error", "Critical", "None"];

    /// <summary>Writes the source of the generated class for <paramref name="type"/>.</summary>
    /// <param name="type">The definitions of the type.</param>
    /// <returns>The source text, with LF line ends.</returns>
    internal static string Write(TypeDefinitions type)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n")
            .Append("// Generated by LogAssertions from the [LoggerMessage] methods of ").Append(type.TypeDisplay).Append(".\n")
            .Append("#nullable enable\n\n");

        var indent = string.Empty;
        if (type.Namespace is not null)
        {
            sb.Append("namespace ").Append(type.Namespace).Append("\n{\n");
            indent = "    ";
        }

        sb.Append(indent).Append("/// <summary>The log definitions of <c>").Append(Xml(type.TypeDisplay))
            .Append("</c>, one per <c>[LoggerMessage]</c> method.</summary>\n")
            .Append(indent).Append("internal static class ").Append(type.ClassName).Append('\n')
            .Append(indent).Append("{\n");

        for (var i = 0; i < type.Methods.Length; i++)
        {
            if (i > 0)
                sb.Append('\n');

            WriteField(sb, indent + "    ", type.Methods[i]);
        }

        sb.Append(indent).Append("}\n");
        if (type.Namespace is not null)
            sb.Append("}\n");

        return sb.ToString();
    }

    /// <summary>Writes the field of one definition.</summary>
    /// <param name="sb">The source being written.</param>
    /// <param name="indent">The indentation of the field.</param>
    /// <param name="method">The definition.</param>
    private static void WriteField(StringBuilder sb, string indent, MethodDefinition method)
    {
        sb.Append(indent).Append("/// <summary>The definition of <c>").Append(Xml(method.MethodName)).Append("</c>.</summary>\n")
            .Append(indent).Append(System.Array.IndexOf(ObjectMembers, method.MethodName) >= 0 ? "public static new readonly " : "public static readonly ")
            .Append("global::LogAssertions.LogDefinition ").Append(Identifier(method.MethodName)).Append(" =\n")
            .Append(indent).Append("    global::LogAssertions.LogDefinition.Create(\n")
            .Append(indent).Append("        new global::Microsoft.Extensions.Logging.EventId(")
            .Append(method.EventId.ToString(CultureInfo.InvariantCulture)).Append(", ").Append(Literal(method.EventName)).Append("),\n")
            .Append(indent).Append("        ").Append(Level(method.Level)).Append(",\n")
            .Append(indent).Append("        ").Append(method.Template is null ? "null" : Literal(method.Template)).Append(",\n")
            .Append(indent).Append("        ").Append(Names(method.PlaceholderNames)).Append(");\n");
    }

    /// <summary>Writes a level as a C# expression.</summary>
    /// <param name="level">The level, or <see langword="null"/>.</param>
    /// <returns>The expression.</returns>
    private static string Level(int? level) => level switch
    {
        null => "null",
        >= 0 and < 7 => "global::Microsoft.Extensions.Logging.LogLevel." + LevelNames[level.Value],
        _ => "(global::Microsoft.Extensions.Logging.LogLevel)" + level.Value.ToString(CultureInfo.InvariantCulture),
    };

    /// <summary>Writes placeholder names as a C# string array.</summary>
    /// <param name="names">The names.</param>
    /// <returns>The array expression.</returns>
    private static string Names(System.Collections.Immutable.ImmutableArray<string> names)
        => names.Length is 0
            ? "global::System.Array.Empty<string>()"
            : "new string[] { " + string.Join(", ", names.Select(Literal)) + " }";

    /// <summary>Writes a string as a C# literal.</summary>
    /// <param name="value">The string.</param>
    /// <returns>The literal.</returns>
    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    /// <summary>Writes a name as a C# identifier, escaping a keyword with <c>@</c>.</summary>
    /// <param name="name">The name.</param>
    /// <returns>The identifier.</returns>
    private static string Identifier(string name)
        => SyntaxFacts.GetKeywordKind(name) is SyntaxKind.None ? name : "@" + name;

    /// <summary>Escapes text for an XML documentation comment.</summary>
    /// <param name="text">The text.</param>
    /// <returns>The escaped text.</returns>
    private static string Xml(string text)
        => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
