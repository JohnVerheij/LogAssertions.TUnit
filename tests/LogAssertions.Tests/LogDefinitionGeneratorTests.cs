    /// <summary>Verifies the equality of the diagnostics in a result.</summary>
    /// <param name="cancellationToken">The test cancellation token.</param>
    [Test]
    public async Task DiagnosticInfoEqualityAsync(CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText("class A { } class B { }", path: "A.cs", cancellationToken: cancellationToken);
        var classes = (await tree.GetRootAsync(cancellationToken)).DescendantNodes().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax>().ToArray();
        var at = LocationInfo.Of(classes[0].GetReference());
        var atSame = LocationInfo.Of(classes[0].GetReference());
        var elsewhere = LocationInfo.Of(classes[1].GetReference());
        var one = new DiagnosticInfo("LOGA001", at, "A");
        var same = new DiagnosticInfo("LOGA001", atSame, "A");

        await Assert.That(one.Equals((object)same)).IsTrue();
        await Assert.That(one.GetHashCode()).IsEqualTo(same.GetHashCode());
        await Assert.That(at!.GetHashCode()).IsEqualTo(atSame!.GetHashCode());
        await Assert.That(at.Equals((object)atSame)).IsTrue();
        await Assert.That(at.Equals((object)"other")).IsFalse();
        await Assert.That(one.Equals(new DiagnosticInfo("LOGA001", at, "B"))).IsFalse();
        await Assert.That(one.Equals(new DiagnosticInfo("LOGA002", at, "A"))).IsFalse();
        await Assert.That(one.Equals(new DiagnosticInfo("LOGA001", elsewhere, "A"))).IsFalse();
        await Assert.That(one.Equals(new DiagnosticInfo("LOGA001", null, "A"))).IsFalse();
        await Assert.That(one.Equals((object)"other")).IsFalse();
        await Assert.That(LocationInfo.Of(null)).IsNull();
        await Assert.That(LocationInfo.Resolve(null, [])).IsEqualTo(Microsoft.CodeAnalysis.Location.None);
        await Assert.That(LocationInfo.Resolve(at, [classes[1].GetLocation(), classes[0].GetLocation()])).IsEqualTo(classes[0].GetLocation());
        await Assert.That(LocationInfo.Resolve(at, [classes[1].GetLocation()]).IsInSource).IsFalse();
        await Assert.That(LocationInfo.Resolve(at, []).GetLineSpan().Path).IsEqualTo("A.cs");
    }
