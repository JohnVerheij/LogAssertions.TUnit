        [assembly: System.Runtime.CompilerServices.InternalsVisibleTo("Consumer")]

        public static class GlobalLog
        {
            [LoggerMessage(EventId = 7, Level = LogLevel.None, Message = "In the global namespace {Value}")]
            public static void @event(ILogger logger, string value) { }
        }

        namespace Shop.Orders
        {
            internal static class OrderLog
            {
                [LoggerMessage(Level = (LogLevel)9, Message = "Out of range")]
