    public async Task SharedClassNameReportsLoga003Async(CancellationToken cancellationToken)
    {
        const string source =
            """
            using Microsoft.Extensions.Logging;

            namespace Shared
            {
                public static class SameLog
                {
                    [LoggerMessage(EventId = 1, Level = LogLevel.Information, Message = "Same")]
                    public static void Same(ILogger logger) { }
                }
            }
            """;
        var first = GeneratorHarness.Product("First", source);
        var second = GeneratorHarness.Product(
            "Second",
            source + """

            namespace Shared
            {
                public static class Other
                {
                    [LoggerMessage(EventId = 2, Level = LogLevel.Information, Message = "Other")]
                    public static void OtherMethod(ILogger logger) { }
                }
            }
            """);
        var run = GeneratorHarness.Run(
            GeneratorHarness.Consumer(
                """
                extern alias first;
                extern alias second;
                [assembly: LogAssertions.GenerateLogDefinitions(typeof(first::Shared.SameLog))]
                [assembly: LogAssertions.GenerateLogDefinitions(typeof(second::Shared.Other))]
                """,
                first.WithAliases(["first"]),
