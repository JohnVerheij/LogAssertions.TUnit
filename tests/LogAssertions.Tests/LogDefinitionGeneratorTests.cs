    /// <summary>Verifies the generated source of a type in the global namespace, character for character.</summary>
    /// <param name="cancellationToken">The test cancellation token.</param>
    [Test]
    public async Task GeneratedSourceOfGlobalTypeIsExactAsync(CancellationToken cancellationToken)
    {
        var product = GeneratorHarness.Product("Shop", ProductSource);
        var run = GeneratorHarness.Run(
            GeneratorHarness.Consumer("[assembly: LogAssertions.GenerateLogDefinitions(typeof(GlobalLog))]", product),
            cancellationToken);

        await Assert.That(run.Errors).IsEmpty();
        await Assert.That(run.Diagnostics).IsEmpty();
        await Assert.That(run.Sources.Keys).IsEquivalentTo(["GlobalLogLogDefinitions.g.cs", "Shop.Orders.OrderLogLogDefinitions.g.cs"]);
        await Assert.That(run.Sources["GlobalLogLogDefinitions.g.cs"]).IsEqualTo(
            """
            // <auto-generated/>
            // Generated by LogAssertions from the [LoggerMessage] methods of GlobalLog.
            #nullable enable

            /// <summary>The log definitions of <c>GlobalLog</c>, one per <c>[LoggerMessage]</c> method.</summary>
            internal static class GlobalLogLogDefinitions
            {
                /// <summary>The definition of <c>event</c>.</summary>
                public static readonly global::LogAssertions.LogDefinition @event =
                    global::LogAssertions.LogDefinition.Create(
                        new global::Microsoft.Extensions.Logging.EventId(7, "event"),
                        global::Microsoft.Extensions.Logging.LogLevel.None,
                        "In the global namespace {Value}",
                        new string[] { "Value" });
            }

            """.ReplaceLineEndings("\n"));
    }

