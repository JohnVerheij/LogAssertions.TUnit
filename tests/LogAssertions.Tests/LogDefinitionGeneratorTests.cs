        await Assert.That(run.Diagnostics[0].GetMessage(System.Globalization.CultureInfo.InvariantCulture))
            .IsEqualTo("Types 'Shared.SameLog' and 'Shared.SameLog' would both generate class 'Shared.SameLogLogDefinitions', so no log definitions are generated for them");
